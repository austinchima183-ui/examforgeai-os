from reportlab.platypus.tableofcontents import TableOfContents

class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))

def add_heading(text, style, level=0):
    key = f'h_{hashlib.md5(text.encode()).hexdigest()[:8]}'
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

# ── Table helper ──
def make_table(headers, rows, widths):
    data = [[Paragraph(f'<b>{h}</b>', ParagraphStyle('th', fontName='FreeSerif-Bold',
             fontSize=9.5, leading=13, textColor=colors.white)) for h in headers]]
    cell_style = ParagraphStyle('td', fontName='FreeSerif', fontSize=9.5, leading=13,
                                textColor=TEXT_PRIMARY)
    for r in rows:
        data.append([Paragraph(str(c), cell_style) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, TABLE_STRIPE]),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ]))
    return t

def callout(text):
    p = Paragraph(text, ParagraphStyle('callout', fontName='FreeSerif-Bold', fontSize=11,
            leading=16, textColor=HEADER_FILL))
    t = Table([[p]], colWidths=[440])
